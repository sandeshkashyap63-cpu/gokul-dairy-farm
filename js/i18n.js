  var LANG_NAMES = { en: "English", hi: "हिन्दी", mr: "मराठी", ta: "தமிழ்", kn: "ಕನ್ನಡ", te: "తెలుగు", gu: "ગુજરાતી" };
  var STORE = "gokul_lang";

  function t(lang, key) {
    var d = T[lang] || T.en;
    return (key in d ? d[key] : (T.en[key] || ""));
  }

  function apply(lang) {
    if (!T[lang]) lang = "en";
    document.documentElement.setAttribute("lang", lang);

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var v = t(lang, el.getAttribute("data-i18n"));
      if (v) el.textContent = v;
    });
    document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      var v = t(lang, el.getAttribute("data-i18n-ph"));
      if (v) el.setAttribute("placeholder", v);
    });

    var cur = document.getElementById("langCurrent");
    if (cur) cur.textContent = LANG_NAMES[lang] || "English";
    document.querySelectorAll("#langMenu li").forEach(function (li) {
      li.setAttribute("aria-selected", li.getAttribute("data-lang") === lang ? "true" : "false");
    });

    try { localStorage.setItem(STORE, lang); } catch (e) {}
    window.__gokulLang = lang;
  }

  function init() {
    var saved = "en";
    try { saved = localStorage.getItem(STORE) || "en"; } catch (e) {}
    apply(saved);

    var sw = document.getElementById("langSwitcher");
    var btn = document.getElementById("langBtn");
    var menu = document.getElementById("langMenu");

    if (btn && sw) {
      btn.addEventListener("click", function (e) {
        e.stopPropagation();
        var open = sw.classList.toggle("open");
        btn.setAttribute("aria-expanded", open ? "true" : "false");
      });
    }
    if (menu) {
      menu.querySelectorAll("li").forEach(function (li) {
        li.addEventListener("click", function () {
          apply(li.getAttribute("data-lang"));
          if (sw) sw.classList.remove("open");
          if (btn) btn.setAttribute("aria-expanded", "false");
        });
      });
    }
    document.addEventListener("click", function () {
      if (sw) sw.classList.remove("open");
      if (btn) btn.setAttribute("aria-expanded", "false");
    });
  }

  window.GokulI18n = { apply: apply, t: t, current: function () { return window.__gokulLang || "en"; } };

  if (document.readyState !== "loading") init();
  else document.addEventListener("DOMContentLoaded", init);
